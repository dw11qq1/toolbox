<p>举例：账户 10 万，风险比例 2%（即最多亏 2000），入场价 50，止损价 47 → 每股风险 3 元 → 应买 <code>2000 ÷ 3 ≈ 666</code> 股，动用资金约 3.33 万，占总仓位 33%。</p>
