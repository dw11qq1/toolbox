<p>仓位定完，还要确认这笔交易值不值得做：<code>风险回报比 = (止盈价 − 入场价) ÷ (入场价 − 止损价)</code>。</p>
<p>常用的门槛是 R:R ≥ 2，也就是赚的空间至少是亏的两倍。它还有个更实用的推论——<b>打平所需胜率 = 1 ÷ (1 + R:R)</b>：R:R 为 2 时，胜率只要 33% 就不亏；R:R 为 1 时，胜率要 50% 才打平；R:R 只有 0.5，胜率得 67% 才能活。</p>
