<h2>把规则翻译成公式</h2>
<p>设：账户资金 <code>C</code>、愿意承受的风险比例 <code>r</code>（比如 2%）、入场价 <code>E</code>、止损价 <code>S</code>。</p>
<ul>
  <li>每股风险 = <code>E − S</code>（买入后跌到止损价，每股亏这么多）</li>
  <li>可承受总亏损 = <code>C × r</code></li>
  <li><b>应买数量 = (C × r) ÷ (E − S)</b></li>
